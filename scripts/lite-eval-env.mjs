// Compose THIS checkout's .env.bench.local from the MAIN checkout's .env plus the Lite
// configuration root .env does not carry. Secrets are copied file-to-file and never printed.
//
//   node scripts/lite-eval-env.mjs [--user=<email>] [--ids=<uuid,uuid>]
//                                  [--model=<provider/model>] [--prompt-version=<id>]
//
// A linked worktree has no .env of its own, so this is the step that makes a paid round
// runnable from anywhere. See scripts/lite-eval-paths.mjs for why the target is named
// `.env.bench.local` and not `.env` or `.env.bench`.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { benchEnvPath, mainCheckout, mainEnv } from './lite-eval-paths.mjs';
import { DEFAULT_EVAL_EMAIL, resolveUserId } from './lite-eval-token.mjs';

const argv = process.argv.slice(2);
const flag = (name) => argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);

const MODEL = flag('model') ?? 'google/gemini-2.5-flash-lite';
const PROMPT_VERSION = flag('prompt-version') ?? '';
const src = mainEnv();

const need = (name, ...alternates) => {
  for (const key of [name, ...alternates]) {
    if (src[key]) return src[key];
  }
  console.error(`${mainCheckout()}/.env has no ${name}`);
  process.exit(1);
};

// The override lifts the per-user daily/monthly Lite caps to 10,000 and concurrency to 2; the
// fleet daily spend ceiling stays the only control. The ids are resolved from the auth
// directory rather than hard-coded, so this works for whichever account holds the eval token
// and no account identifier is committed to an open repo.
let overrideIds = flag('ids') ?? src.AI_LITE_OVERRIDE_USER_IDS ?? '';
if (!overrideIds) {
  const email = flag('user') ?? DEFAULT_EVAL_EMAIL;
  try {
    overrideIds = await resolveUserId(email);
  } catch (error) {
    console.error(`Could not resolve the eval user id: ${error.message}`);
    console.error('Pass --ids=<uuid,uuid> to skip the lookup.');
    process.exit(1);
  }
}

const OUT = benchEnvPath();
// A token stamped earlier is still valid; recomposing the configuration must not silently
// throw the identity away and leave the round runner reporting a missing token.
const carriedToken = existsSync(OUT)
  ? readFileSync(OUT, 'utf8')
      .replace(/^\uFEFF/, '')
      .split(/\r?\n/)
      .find((line) => line.startsWith('NOACG_LITE_EVAL_BEARER_TOKEN='))
  : undefined;

const lines = [
  '# Generated by scripts/lite-eval-env.mjs for a paid Lite eval round in this checkout.',
  '# Gitignored, local only, safe to delete. Read by `vite --mode bench` (npm run dev:bench)',
  '# - NOT by the e2e suite.',
  '',
  `AI_GATEWAY_API_KEY=${need('AI_GATEWAY_API_KEY')}`,
  `AI_KEY_ENCRYPTION_SECRET=${need('AI_KEY_ENCRYPTION_SECRET')}`,
  '',
  `VITE_SUPABASE_URL=${need('VITE_SUPABASE_URL', 'SUPABASE_URL')}`,
  `VITE_SUPABASE_ANON_KEY=${need('VITE_SUPABASE_ANON_KEY', 'SUPABASE_ANON_KEY')}`,
  `SUPABASE_SERVICE_ROLE_KEY=${need('SUPABASE_SERVICE_ROLE_KEY', 'SUPABASE_SECRET_KEY')}`,
  // liteLedgerConfigured() requires a salt of at least 16 characters or Lite answers
  // `not-configured` with everything else correct. It salts the ANONYMOUS per-IP quota hash
  // only; an eval round is identity-bound, so a fixed local value changes nothing but the
  // ip_hash column. Root .env has none, which is why a local one is written here.
  'IP_HASH_SALT=noacg-local-lite-eval-salt',
  '',
  '# Lite, configured exactly as production is: the same primary and second attempt, and the',
  '# same audited gateway provider slug (docs/MODEL_ROUTE_AUDITS.md - gemini-2.5-flash-lite is',
  '# served by vertex under ZDR). The route price comes from the approved-route catalog, so no',
  '# AI_LITE_PRICING_JSON is needed.',
  'AI_LITE_ENABLED=1',
  'AI_LITE_PRIMARY_PROVIDER=vercel',
  `AI_LITE_PRIMARY_MODEL=${MODEL}`,
  'AI_LITE_FALLBACK_PROVIDER=vercel',
  `AI_LITE_FALLBACK_MODEL=${MODEL}`,
  'AI_LITE_GATEWAY_PROVIDERS=vertex',
  'AI_LITE_REQUIRE_ZDR=1',
  `AI_LITE_OVERRIDE_USER_IDS=${overrideIds}`,
];

// Left unset by default so the CODE default is what gets measured and what the ledger records
// - a stale pin here would silently benchmark a prompt the product no longer serves.
if (PROMPT_VERSION) lines.push(`AI_LITE_PROMPT_VERSION=${PROMPT_VERSION}`);
if (carriedToken) lines.push('', carriedToken);
lines.push('');

writeFileSync(OUT, `${lines.join('\n')}\n`, 'utf8');
console.log(`wrote ${OUT} (${lines.length} lines, secrets copied not printed)`);
console.log(`  route ${MODEL} via vercel/vertex, ZDR required`);
console.log(`  quota override for ${overrideIds}`);
console.log(carriedToken ? '  carried the existing bearer token over' : '  no bearer token yet - run scripts/lite-eval-stamp.mjs');
